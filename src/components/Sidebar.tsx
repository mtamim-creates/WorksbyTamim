import { Coins, Bitcoin, TrendingUp, ChevronRight } from 'lucide-react';
import type { AssetConfig, Category } from '../lib/types';
import { CATEGORIES } from '../lib/assets';

const CATEGORY_ICONS: Record<Category, typeof Coins> = {
  gold: Coins,
  crypto: Bitcoin,
  stocks: TrendingUp,
};

interface Props {
  assets: AssetConfig[];
  activeId: string;
  onSelect: (id: string) => void;
}

export default function Sidebar({ assets, activeId, onSelect }: Props) {
  const grouped = CATEGORIES.map((c) => ({
    ...c,
    icon: CATEGORY_ICONS[c.id],
    items: assets.filter((a) => a.category === c.id),
  })).filter((g) => g.items.length > 0);

  return (
    <aside className="w-full shrink-0 lg:w-72">
      <div className="flex gap-3 overflow-x-auto pb-2 lg:flex-col lg:gap-5 lg:overflow-visible lg:pb-0">
        {grouped.map((group) => (
          <div key={group.id} className="w-60 shrink-0 lg:w-full">
            <div className="mb-2 flex items-center gap-2 px-1">
              <group.icon className="h-3.5 w-3.5 text-slate-500" />
              <span className="text-[10px] font-bold uppercase tracking-[0.14em] text-slate-500">
                {group.label}
              </span>
              <span className="ml-auto font-mono text-[10px] text-slate-600">
                {group.items.length}
              </span>
            </div>

            <div className="space-y-1">
              {group.items.map((asset) => {
                const active = asset.id === activeId;
                const up = asset.dayChange >= 0;
                return (
                  <button
                    key={asset.id}
                    onClick={() => onSelect(asset.id)}
                    className={`group flex w-full items-center gap-3 rounded-xl border px-3 py-2.5 text-left transition-all duration-150 ${
                      active
                        ? 'border-cyan-400/30 bg-cyan-400/[0.08] shadow-[0_0_20px_rgba(34,211,238,0.08)]'
                        : 'border-transparent hover:border-slate-700/60 hover:bg-slate-800/40'
                    }`}
                  >
                    <span
                      className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg font-mono text-[11px] font-bold"
                      style={{
                        backgroundColor: `${asset.color}1f`,
                        color: asset.color,
                        border: `1px solid ${asset.color}33`,
                      }}
                    >
                      {asset.id.slice(0, 3)}
                    </span>

                    <span className="min-w-0 flex-1">
                      <span className="block truncate text-[13px] font-semibold text-slate-200">
                        {asset.symbol}
                      </span>
                      <span className="block truncate text-[11px] text-slate-500">
                        {asset.name}
                      </span>
                    </span>

                    <span
                      className={`flex items-center gap-1 rounded-md px-1.5 py-0.5 font-mono text-[11px] tabular-nums ${
                        up
                          ? 'bg-emerald-400/10 text-emerald-400'
                          : 'bg-rose-400/10 text-rose-400'
                      }`}
                    >
                      {up ? '+' : ''}
                      {asset.dayChange.toFixed(2)}%
                    </span>

                    <ChevronRight
                      className={`h-4 w-4 shrink-0 transition-transform ${
                        active
                          ? 'text-cyan-400'
                          : 'text-slate-700 group-hover:translate-x-0.5 group-hover:text-slate-500'
                      }`}
                    />
                  </button>
                );
              })}
            </div>
          </div>
        ))}
      </div>

      <div className="mt-6 hidden rounded-xl border border-slate-800/80 bg-slate-900/40 p-4 lg:block">
        <p className="text-[10px] font-bold uppercase tracking-[0.14em] text-slate-600">
          Data Source
        </p>
        <p className="mt-1.5 text-[11px] leading-relaxed text-slate-500">
          Simulated market feed. Predictions generated by on-device OLS and
          LSTM models for demonstration purposes.
        </p>
        <div className="mt-3 flex items-center gap-2">
          <span className="h-1.5 w-1.5 rounded-full bg-emerald-400" />
          <span className="font-mono text-[10px] text-slate-600">
            latency 12ms · feed stable
          </span>
        </div>
      </div>
    </aside>
  );
}
